import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appSource = await readFile(resolve(root, "src/site/App.tsx"), "utf8");
const vercelConfig = await readFile(resolve(root, "vercel.json"), "utf8");

test("interactive preview is clearly labeled as sample and makes no gateway calls", () => {
  assert.match(appSource, /SIMULATED DATA/);
  assert.match(appSource, /No backend or AI endpoint is called/);
  assert.match(appSource, /Illustrative text · not generated by an AI/);
  assert.doesNotMatch(appSource, /\bfetch\s*\(/);
  assert.doesNotMatch(appSource, /https?:\/\/127\.0\.0\.1:8787\/v1\/chat\/completions/);
});

test("external source, docs and video URLs come from public Vite configuration", () => {
  assert.match(appSource, /VITE_GITHUB_URL/);
  assert.match(appSource, /VITE_DEMO_VIDEO_URL/);
  assert.match(appSource, /VITE_DOCS_URL/);
  assert.doesNotMatch(appSource, /SUBBRIDGE_TOKEN\s*=\s*["'][A-Fa-f0-9]{32,}["']/);
});

test("Vercel SPA fallback targets the built static entry point", () => {
  const parsed = JSON.parse(vercelConfig);
  assert.deepEqual(parsed.rewrites, [{ source: "/(.*)", destination: "/index.html" }]);
});
